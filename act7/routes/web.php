<?php

use App\Http\Controllers\DashboardController;
use Illuminate\Support\Facades\Auth;
use Illuminate\Support\Facades\Route;

/*
|--------------------------------------------------------------------------
| Landing Page (guests only)
|--------------------------------------------------------------------------
| The 'guest' middleware only lets unauthenticated users see this page.
| If a logged-in user opens "/", Laravel redirects them to the dashboard.
*/
Route::get('/', function () {
    return view('landingpage');
})->middleware('guest')->name('landing');

/*
|--------------------------------------------------------------------------
| Authentication routes (login, register, logout, password reset...)
|--------------------------------------------------------------------------
*/
Auth::routes();

/*
|--------------------------------------------------------------------------
| Dashboard (authenticated users only)
|--------------------------------------------------------------------------
| The 'auth' middleware blocks guests, even if they type /dashboard
| directly in the browser. They are redirected to the login page.
*/
Route::get('/dashboard', [DashboardController::class, 'index'])
    ->middleware('auth')
    ->name('dashboard');

// Old route generated by Laravel UI: now it sends users to the dashboard.
Route::redirect('/home', '/dashboard')->name('home');
